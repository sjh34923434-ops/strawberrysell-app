// ── 키워드 매칭 함수 ────────────────────────────────────────────────────────────
function normalize(s: string): string {
  return s
    .replace(/^[/?！!]/g, '')   // 앞의 /  ? ! 제거
    .replace(/\s+/g, '')         // 공백 제거
    .replace(/[_\-·]/g, '')      // 특수문자 제거
    .toLowerCase()
}

export function findAnswer(input: string): FAQItem | null {
  const q = normalize(input)
  if (!q) return null

  // 1순위: 키워드 완전 포함
  const exact = FAQ_LIST.find(item =>
    item.keywords.some(kw => q.includes(normalize(kw)) || normalize(kw).includes(q))
  )
  if (exact) return exact

  // 2순위: 부분 2글자 이상 겹침
  const partial = FAQ_LIST.find(item =>
    item.keywords.some(kw => {
      const nkw = normalize(kw)
      return nkw.length >= 2 && (q.includes(nkw.slice(0, 2)) || nkw.includes(q.slice(0, 2)))
    })
  )
  return partial ?? null
}

